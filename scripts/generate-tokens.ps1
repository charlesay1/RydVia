param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$tokens = Get-Content -LiteralPath (Join-Path $root 'design/tokens.json') -Raw | ConvertFrom-Json
$dart = [System.Collections.Generic.List[string]]::new()
$css = [System.Collections.Generic.List[string]]::new()
$dart.Add('// dart format off')
$dart.Add("// Generated by scripts/generate-tokens.ps1. Edit design/tokens.json.")
$dart.Add("import 'package:flutter/material.dart';")
$css.Add('/* Generated by scripts/generate-tokens.ps1. Edit design/tokens.json. */')
$css.Add(':root {')
$css.Add('  --rv-font: var(--font-manrope, Manrope), system-ui, sans-serif;')
function Kebab([string]$value) { return [regex]::Replace($value, '[A-Z]', { param($match) '-' + $match.Value.ToLowerInvariant() }) }
foreach ($section in @('colors', 'spacing', 'radius', 'motion', 'iconSize', 'elevation')) {
    $className = 'RydVia' + $section.Substring(0, 1).ToUpperInvariant() + $section.Substring(1)
    $dart.Add("abstract final class $className {")
    foreach ($property in $tokens.$section.PSObject.Properties) {
        $name = $property.Name
        $value = $property.Value
        $cssName = '--rv-' + (Kebab $section) + '-' + (Kebab $name)
        if ($section -eq 'colors') {
            $dart.Add("  static const $name = Color(0xFF$($value.Substring(1)));")
            $css.Add("  ${cssName}: $value;")
        } elseif ($section -eq 'motion') {
            $dart.Add("  static const $name = Duration(milliseconds: $value);")
            $css.Add("  ${cssName}: ${value}ms;")
        } else {
            $dart.Add("  static const double $name = $value;")
            $unit = if ($section -eq 'elevation') { '' } else { 'px' }
            $css.Add("  ${cssName}: ${value}${unit};")
        }
    }
    $dart.Add('}')
}
$dart.Add('abstract final class RydViaTypography {')
foreach ($property in $tokens.typography.PSObject.Properties) {
    $name = $property.Name
    $value = $property.Value
    $height = $value.height.ToString([Globalization.CultureInfo]::InvariantCulture)
    $dart.Add("  static const $name = TextStyle(fontFamily: 'Manrope', package: 'rydvia_ui', fontSize: $($value.size), fontWeight: FontWeight.w$($value.weight), height: $height);")
    $css.Add("  --rv-type-${name}-size: $($value.size)px;")
    $css.Add("  --rv-type-${name}-weight: $($value.weight);")
    $css.Add("  --rv-type-${name}-height: $height;")
}
$dart.Add('}')
$css.Add('}')
foreach ($theme in $tokens.themes.PSObject.Properties) {
    $themeClass = 'RydVia' + $theme.Name.Substring(0, 1).ToUpperInvariant() + $theme.Name.Substring(1) + 'Tokens'
    $dart.Add("abstract final class $themeClass {")
    foreach ($property in $theme.Value.PSObject.Properties) { $dart.Add("  static const $($property.Name) = RydViaColors.$($property.Value);") }
    $dart.Add('}')
    $selector = if ($theme.Name -eq 'light') { ':root, [data-theme="light"]' } else { '[data-theme="dark"]' }
    $css.Add("$selector {")
    $css.Add("  color-scheme: $($theme.Name);")
    foreach ($property in $theme.Value.PSObject.Properties) {
        $css.Add("  --rv-$(Kebab $property.Name): var(--rv-colors-$(Kebab $property.Value));")
    }
    $css.Add('}')
}
$css.Add('@media (prefers-color-scheme: dark) {')
$css.Add('  :root:not([data-theme="light"]):not([data-theme="dark"]) {')
$css.Add('    color-scheme: dark;')
foreach ($property in $tokens.themes.dark.PSObject.Properties) {
    $css.Add("    --rv-$(Kebab $property.Name): var(--rv-colors-$(Kebab $property.Value));")
}
$css.Add('  }')
$css.Add('}')
$css.Add('@media (prefers-reduced-motion: reduce) {')
$css.Add('  :root {')
foreach ($property in $tokens.motion.PSObject.Properties) { $css.Add("    --rv-motion-$($property.Name): 0ms;") }
$css.Add('  }')
$css.Add('}')
$outputs = @{
    'packages/rydvia_ui/lib/src/theme/tokens.g.dart' = ($dart -join "`n") + "`n"
    'packages/rydvia_ui/web/tokens.css' = ($css -join "`n") + "`n"
}
foreach ($role in @('customer','driver','business')) {
    $prefix = "apps/${role}_app"
    if (!(Test-Path -LiteralPath (Join-Path $root "$prefix/android"))) { continue }
    foreach ($themeName in @('light','dark')) {
        $folder = if ($themeName -eq 'light') { 'values' } else { 'values-night' }
        $hex = $tokens.colors.($tokens.themes.$themeName.background)
        $outputs["$prefix/android/app/src/main/res/$folder/colors.xml"] = "<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<resources><color name=`"rydvia_background`">$hex</color></resources>`n"
        $parent = if ($themeName -eq 'light') { '@android:style/Theme.Light.NoTitleBar' } else { '@android:style/Theme.Black.NoTitleBar' }
        $outputs["$prefix/android/app/src/main/res/$folder/styles.xml"] = "<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<resources><style name=`"LaunchTheme`" parent=`"$parent`"><item name=`"android:windowBackground`">@color/rydvia_background</item></style><style name=`"NormalTheme`" parent=`"$parent`"><item name=`"android:windowBackground`">@color/rydvia_background</item></style></resources>`n"
    }
    foreach ($folder in @('drawable','drawable-v21')) {
        $outputs["$prefix/android/app/src/main/res/$folder/launch_background.xml"] = "<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<layer-list xmlns:android=`"http://schemas.android.com/apk/res/android`"><item android:drawable=`"@color/rydvia_background`" /></layer-list>`n"
    }
    $colors = @()
    foreach ($themeName in @('light','dark')) {
        $hex = $tokens.colors.($tokens.themes.$themeName.background)
        $color = [ordered]@{ idiom = 'universal'; color = [ordered]@{ 'color-space' = 'srgb'; components = [ordered]@{ red = ([Convert]::ToInt32($hex.Substring(1,2),16) / 255.0).ToString('F6',[Globalization.CultureInfo]::InvariantCulture); green = ([Convert]::ToInt32($hex.Substring(3,2),16) / 255.0).ToString('F6',[Globalization.CultureInfo]::InvariantCulture); blue = ([Convert]::ToInt32($hex.Substring(5,2),16) / 255.0).ToString('F6',[Globalization.CultureInfo]::InvariantCulture); alpha = '1.000000' } } }
        if ($themeName -eq 'dark') { $color.appearances = @([ordered]@{ appearance = 'luminosity'; value = 'dark' }) }
        $colors += $color
    }
    # Ordered JSON output prevents token checks from depending on hashtable order.
    $colorJson = [ordered]@{ colors = $colors; info = [ordered]@{ author = 'xcode'; version = 1 } } | ConvertTo-Json -Depth 8 -Compress
    $outputs["$prefix/ios/Runner/Assets.xcassets/LaunchBackground.colorset/Contents.json"] = $colorJson + "`n"
    $outputs["$prefix/ios/Runner/Base.lproj/LaunchScreen.storyboard"] = @'
<?xml version="1.0" encoding="UTF-8"?>
<document type="com.apple.InterfaceBuilder3.CocoaTouch.Storyboard.XIB" version="3.0" targetRuntime="iOS.CocoaTouch" useAutolayout="YES" launchScreen="YES" useTraitCollections="YES" colorMatched="YES" initialViewController="root-controller">
  <dependencies><deployment identifier="iOS"/><plugIn identifier="com.apple.InterfaceBuilder.IBCocoaTouchPlugin" version="21507"/><capability name="Named colors" minToolsVersion="9.0"/></dependencies>
  <scenes><scene sceneID="launch-scene"><objects><viewController id="root-controller" sceneMemberID="viewController"><view key="view" contentMode="scaleToFill" id="launch-view"><rect key="frame" x="0.0" y="0.0" width="414" height="896"/><autoresizingMask key="autoresizingMask" widthSizable="YES" heightSizable="YES"/><color key="backgroundColor" name="LaunchBackground"/></view></viewController><placeholder placeholderIdentifier="IBFirstResponder" id="first-responder" sceneMemberID="firstResponder"/></objects></scene></scenes>
  <resources><namedColor name="LaunchBackground"><color red="0.980392" green="0.968627" blue="0.949020" alpha="1" colorSpace="custom" customColorSpace="sRGB"/></namedColor></resources>
</document>
'@
    $outputs["$prefix/ios/Runner/Base.lproj/LaunchScreen.storyboard"] += "`n"
}
foreach ($relative in $outputs.Keys) {
    $path = Join-Path $root $relative
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $outputs[$relative]) { throw "Generated tokens are stale: $relative" }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path $path -Parent)) | Out-Null
        [IO.File]::WriteAllText($path, $outputs[$relative], [Text.UTF8Encoding]::new($false))
    }
}
Write-Output 'Token outputs match.'
